#!/usr/bin/env python3
"""Generate cloud-init files (user-data, network-config, meta-data) that turn a freshly flashed
Raspberry Pi OS Lite (Trixie, Imager 2.0+) into a working fuelhub Pi on first boot.
No keyboard, mouse, monitor, or SSH session needed; no internet needed.

  ./provision/make_sd_config.py server --out build/server     # red hub, 10.0.100.40, Modbus PLC
  ./provision/make_sd_config.py peer   --out build/peer       # blue hub, 10.0.100.41
  ./provision/make_sd_config.py server --boot /Volumes/bootfs # write straight onto a mounted SD card

Everything is embedded (base64): the code release, fuelhub-apply, the systemd unit, role settings.
Stdlib only.
"""
import argparse, base64, hashlib, io, os, re, shlex, subprocess, sys, tarfile, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def read_conf(role):
    conf = {}
    with open(os.path.join(ROOT, "provision", "roles", role + ".conf")) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if "=" in line:
                k, v = line.split("=", 1)
                conf[k.strip()] = v.strip()
    return conf


def git_version():
    try:
        v = subprocess.check_output(["git", "-C", ROOT, "describe", "--always", "--dirty", "--abbrev=7"],
                                    stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        v = time.strftime("%Y%m%d%H%M%S")
    if v.endswith("-dirty"):
        v += "-" + time.strftime("%H%M%S")
    return re.sub(r"[^A-Za-z0-9._-]", "", v)


def release_tarball(version):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for name, data in (("fuelhub.py", open(os.path.join(ROOT, "src", "fuelhub.py"), "rb").read()),
                           ("VERSION", (version + "\n").encode())):
            ti = tarfile.TarInfo(name); ti.size = len(data); ti.mtime = 0; ti.mode = 0o644
            tar.addfile(ti, io.BytesIO(data))
    return buf.getvalue()


def render_unit(conf):
    s = open(os.path.join(ROOT, "deploy", "fuelhub.service.in")).read()
    for k, v in {"@ROLE@": conf["ROLE"], "@ALLIANCE@": conf["ALLIANCE"], "@PEER_IP@": conf["PEER_IP"],
                 "@SERVE_FLAG@": "--serve " if conf["SERVE"] == "1" else ""}.items():
        s = s.replace(k, v)
    return s


def b64(b):
    return base64.b64encode(b).decode()


def write_file(path, data, mode="0644"):
    return ["  - path: %s" % path, "    owner: root:root", "    permissions: '%s'" % mode,
            "    encoding: b64", "    content: %s" % b64(data)]


def build(role, ssh_keys, user, password_hash, timezone):
    conf = read_conf(role)
    version = git_version()
    tarball = release_tarball(version)
    sha = hashlib.sha256(tarball).hexdigest()
    role_env = "\n".join("%s=%s" % (k, v) for k, v in conf.items()) + "\nPORT=502\n"
    apply_sh = open(os.path.join(ROOT, "deploy", "fuelhub-apply.sh"), "rb").read()
    journald = b"[Journal]\nStorage=volatile\nRuntimeMaxUse=50M\n"   # no log writes to the SD card

    ud = ["#cloud-config", "# Generated by provision/make_sd_config.py for role=%s version=%s" % (role, version),
          "hostname: %s" % conf["HOSTNAME_NEW"], "manage_etc_hosts: true", "timezone: %s" % timezone,
          "enable_ssh: true", "ssh_pwauth: false", "users:",
          "  - name: %s" % user, "    groups: users,sudo,gpio", "    shell: /bin/bash",
          "    sudo: ALL=(ALL) NOPASSWD:ALL"]
    if password_hash:
        ud += ["    lock_passwd: false", "    passwd: %s" % password_hash]
    else:
        ud += ["    lock_passwd: true"]
    ud += ["    ssh_authorized_keys:"] + ["      - %s" % k for k in ssh_keys]
    ud += ["  - name: fuelhub", "    system: true", "    shell: /usr/sbin/nologin", "    groups: gpio",
           "    lock_passwd: true", "    no_create_home: true"]
    ud += ["write_files:"]
    ud += ["  # role settings, read by fuelhub-apply"] + write_file("/etc/fuelhub/role.env", role_env.encode())
    ud += ["  # on-Pi update tool (used for first install and every OTA)"] + \
        write_file("/usr/local/sbin/fuelhub-apply", apply_sh, "0755")
    ud += ["  # first release"] + write_file("/var/lib/fuelhub/seed.tar.gz", tarball) + \
        write_file("/var/lib/fuelhub/seed.tar.gz.sha256", ("%s  seed.tar.gz\n" % sha).encode())
    ud += ["  # service"] + write_file("/etc/systemd/system/fuelhub.service", render_unit(conf).encode())
    ud += ["  # keep logs in RAM"] + write_file("/etc/systemd/journald.conf.d/volatile.conf", journald)
    ud += ["runcmd:",
           "  - [systemctl, daemon-reload]",
           "  - [systemctl, restart, systemd-journald]",
           "  - [systemctl, enable, fuelhub]",
           "  - [/usr/local/sbin/fuelhub-apply, /var/lib/fuelhub/seed.tar.gz]",
           "  - [logger, -t, fuelhub-firstboot, 'fuelhub %s provisioned as %s']" % (version, role)]
    ud += ["final_message: 'fuelhub %s ready after $UPTIME seconds'" % version]

    nc = ["network:", "  version: 2", "  ethernets:", "    eth0:", "      renderer: NetworkManager",
          "      dhcp4: false", "      dhcp6: false", "      addresses:", "        - %s/%s" % (conf["IP"], conf["PREFIX"]),
          "      routes:", "        - to: default", "          via: %s" % conf["GATEWAY"]]
    md = ["instance_id: fuelhub-%s-%s" % (role, version), "local-hostname: %s" % conf["HOSTNAME_NEW"]]
    return {"user-data": "\n".join(ud) + "\n", "network-config": "\n".join(nc) + "\n",
            "meta-data": "\n".join(md) + "\n"}, version


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("role", choices=["server", "peer"])
    ap.add_argument("--out", help="directory to write the 3 files into")
    ap.add_argument("--boot", help="mounted boot partition of the freshly flashed SD card (writes there)")
    ap.add_argument("--ssh-key-file", action="append",
                    help="public key file (repeatable; default ~/.ssh/id_ed25519.pub or id_rsa.pub)")
    ap.add_argument("--user", default="pi")
    ap.add_argument("--password-hash", help="optional: `openssl passwd -6` hash for console/SSH password login "
                                           "(ssh_pwauth stays off; the password only helps at a keyboard)")
    ap.add_argument("--timezone", default="Asia/Jerusalem")
    a = ap.parse_args()
    if not (a.out or a.boot):
        ap.error("give --out DIR and/or --boot MOUNTPOINT")
    paths = a.ssh_key_file or [p for p in (os.path.expanduser("~/.ssh/id_ed25519.pub"),
                                           os.path.expanduser("~/.ssh/id_rsa.pub")) if os.path.exists(p)][:1]
    if not paths:
        ap.error("no SSH public key found; pass --ssh-key-file (create one with: ssh-keygen -t ed25519)")
    keys = [open(p).read().strip() for p in paths]
    if not all(k.startswith(("ssh-", "ecdsa-", "sk-")) for k in keys):
        ap.error("that does not look like a PUBLIC key file (.pub)")
    files, version = build(a.role, keys, a.user, a.password_hash, a.timezone)
    for d in filter(None, (a.out, a.boot)):
        os.makedirs(d, exist_ok=True)
        for name, text in files.items():
            with open(os.path.join(d, name), "w", newline="\n") as f:
                f.write(text)
        print("wrote user-data, network-config, meta-data to %s (role=%s, version=%s)" % (d, a.role, version))


if __name__ == "__main__":
    main()
